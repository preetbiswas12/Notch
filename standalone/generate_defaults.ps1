# Parses the ==WindhawkModSettings== YAML block out of dynamic-island-for-windows.wh.cpp
# and emits island_defaults.h: a name -> default table used by the standalone
# runtime as the wired-in fallback for Wh_GetIntSetting / Wh_GetStringSetting.
param(
    [string]$SourcePath = (Join-Path $PSScriptRoot "..\mod\dynamic-island-for-windows.wh.cpp"),
    [string]$OutPath = (Join-Path $PSScriptRoot "island_defaults.h")
)

$ErrorActionPreference = "Stop"
$lines = [System.IO.File]::ReadAllLines($SourcePath)

# Locate the settings block.
$startIdx = -1
$endIdx = -1
for ($i = 0; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -match '^// ==WindhawkModSettings==') { $startIdx = $i; break }
}
for ($i = $startIdx + 1; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -match '^// ==/WindhawkModSettings==') { $endIdx = $i; break }
}
if ($startIdx -lt 0 -or $endIdx -lt 0) { throw "settings block not found" }

$group = ""
$entries = New-Object System.Collections.Generic.List[object]
$patternLeaf = '^ {2}- ([A-Za-z][A-Za-z0-9]*): (.+)$'
$patternGroup = '^- ([A-Za-z][A-Za-z0-9]*):\s*$'

for ($i = $startIdx + 1; $i -lt $endIdx; $i++) {
    $line = $lines[$i]
    if ($line -match $patternGroup) {
        $group = $Matches[1]
        continue
    }
    if ($line -match $patternLeaf) {
        $leaf = $Matches[1]
        $raw = $Matches[2].Trim()
        $fullKey = if ($group) { "$group.$leaf" } else { $leaf }

        $isInt = 0
        $intVal = 0
        $strVal = ""

        if ($raw -eq 'true') {
            $isInt = 1; $intVal = 1
        } elseif ($raw -eq 'false') {
            $isInt = 1; $intVal = 0
        } elseif ($raw -match '^-?\d+$') {
            $isInt = 1; $intVal = [int]$raw
        } elseif ($raw.StartsWith("'") -and $raw.EndsWith("'") -and $raw.Length -ge 2) {
            $strVal = $raw.Substring(1, $raw.Length - 2).Replace("''", "'")
        } elseif ($raw.StartsWith('"') -and $raw.EndsWith('"') -and $raw.Length -ge 2) {
            $strVal = $raw.Substring(1, $raw.Length - 2)
        } else {
            $strVal = $raw
        }

        # Replace: first definition wins.
        $existing = $entries | Where-Object { $_.Key -eq $fullKey }
        if ($existing) {
            Write-Output ("duplicate key kept-first: {0} (line {1})" -f $fullKey, ($i + 1))
            continue
        }
        $entries.Add([pscustomobject]@{ Key = $fullKey; IsInt = $isInt; IntVal = $intVal; StrVal = $strVal })
    }
}

# Sort alphabetically for a deterministic header.
$sorted = $entries | Sort-Object Key

function Esc-C([string]$s) {
    if ($s.Contains([char]92)) { $s = $s.Replace('\', '\\') }
    if ($s.Contains([char]34)) { $s = $s.Replace('"', '\"') }
    return $s
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// AUTO-GENERATED by generate_defaults.ps1 from dynamic-island-for-windows.wh.cpp")
[void]$sb.AppendLine("// ==WindhawkModSettings== YAML defaults. Do not edit by hand - regenerate.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("struct IslandDefaultEntry {")
[void]$sb.AppendLine("    const wchar_t* name;")
[void]$sb.AppendLine("    int isInt;")
[void]$sb.AppendLine("    int intVal;")
[void]$sb.AppendLine("    const wchar_t* strVal;")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("inline constexpr IslandDefaultEntry kIslandDefaults[] = {")
foreach ($e in $sorted) {
    $keyC = Esc-C $e.Key
    if ($e.IsInt) {
        [void]$sb.AppendLine('    {L"' + $keyC + '", 1, ' + $e.IntVal + ', L""},')
    } else {
        $v = Esc-C $e.StrVal
        [void]$sb.AppendLine('    {L"' + $keyC + '", 0, 0, L"' + $v + '"},')
    }
}
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("inline constexpr size_t kIslandDefaultCount =")
[void]$sb.AppendLine("    sizeof(kIslandDefaults) / sizeof(kIslandDefaults[0]);")

[System.IO.File]::WriteAllText($OutPath, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Output ("wrote {0} defaults" -f $sorted.Count)
Write-Output ("out: {0}" -f $OutPath)
